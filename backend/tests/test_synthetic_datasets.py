"""The persisted synthetic datasets behind the real Stage C/D engines
(docs/stage-c-d-integration-plan.md §6/§7): `data/synthetic_forcing/<case_id>/current_field.json`
and `data/synthetic_ais/<case_id>/scenario.json`, generated by
`backend/scripts/generate_synthetic_datasets.py`. These tests catch the file going
missing or drifting out of sync with the generation code -- the same role
`test_contracts.py`'s fixture-validation tests play for the mock data."""

from __future__ import annotations

import json

import pytest

from app.core.errors import CaseNotFoundError
from app.core.paths import CASES_DIR, SYNTHETIC_AIS_DIR, SYNTHETIC_FORCING_DIR
from app.integrations.real.ais_data import load_scenario
from app.integrations.real.drift_physics import derive_idealized_current_parameters
from app.integrations.real.forcing_data import load_current_parameters

CASE_IDS = sorted(p.name for p in CASES_DIR.iterdir() if p.is_dir())


@pytest.mark.parametrize("case_id", CASE_IDS)
def test_current_field_file_exists_and_loads(case_id: str):
    params = load_current_parameters(case_id)
    assert 0.0 < params.base_speed_mps
    assert 0.0 <= params.base_bearing_deg < 360.0
    assert "synthetic" in params.disclosure.lower()


@pytest.mark.parametrize("case_id", CASE_IDS)
def test_current_field_matches_the_generation_code(case_id: str):
    # Guards against the persisted file drifting out of sync with
    # derive_idealized_current_parameters() -- e.g. someone changes the seed formula
    # without re-running the generation script.
    expected_speed, expected_bearing = derive_idealized_current_parameters(case_id)
    params = load_current_parameters(case_id)
    assert params.base_speed_mps == pytest.approx(expected_speed, abs=1e-3)
    assert params.base_bearing_deg == pytest.approx(expected_bearing, abs=1e-1)


def test_current_field_missing_case_raises_case_not_found():
    with pytest.raises(CaseNotFoundError):
        load_current_parameters("OS-does-not-exist")


@pytest.mark.parametrize("case_id", CASE_IDS)
def test_ais_scenario_file_exists_and_loads(case_id: str):
    tracks = load_scenario(case_id)
    assert len(tracks) >= 1
    for track in tracks:
        assert track.vessel_id
        assert len(track.reports) >= 1


def test_ais_scenario_missing_case_raises_case_not_found():
    with pytest.raises(CaseNotFoundError):
        load_scenario("OS-does-not-exist")


@pytest.mark.parametrize("case_id", CASE_IDS)
def test_ais_scenario_raw_json_has_disclosure(case_id: str):
    path = SYNTHETIC_AIS_DIR / case_id / "scenario.json"
    with path.open(encoding="utf-8") as f:
        raw = json.load(f)
    assert "synthetic" in raw["disclosure"].lower()
    assert "live vessel traffic" in raw["disclosure"].lower()


@pytest.mark.parametrize("case_id", CASE_IDS)
def test_current_field_file_lives_under_synthetic_forcing_dir(case_id: str):
    assert (SYNTHETIC_FORCING_DIR / case_id / "current_field.json").exists()
